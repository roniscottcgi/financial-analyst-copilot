CREATE TABLE IF NOT EXISTS customers (
  customer_id INT PRIMARY KEY,
  customer_name VARCHAR(120),
  segment VARCHAR(40),
  region VARCHAR(40),
  status VARCHAR(20),
  created_date DATE
);


CREATE TABLE IF NOT EXISTS products (
  product_id INT PRIMARY KEY,
  product_name VARCHAR(120),
  product_family VARCHAR(60),
  support_tier VARCHAR(30),
  active_flag CHARACTER(1)
);


CREATE TABLE IF NOT EXISTS agents (
  agent_id INT PRIMARY KEY,
  agent_name VARCHAR(120),
  team_name VARCHAR(60),
  location VARCHAR(40),
  skill_level VARCHAR(20)
);


CREATE TABLE IF NOT EXISTS support_tickets (
  ticket_id INT PRIMARY KEY,
  customer_id INT,
  product_id INT,
  agent_id INT,
  opened_date DATE,
  priority VARCHAR(20),
  status VARCHAR(20),
  issue_category VARCHAR(60),
  resolution_code VARCHAR(60),
  FOREIGN KEY (customer_id) REFERENCES customers(customer_id),
  FOREIGN KEY (product_id) REFERENCES products(product_id),
  FOREIGN KEY (agent_id) REFERENCES agents(agent_id)
);


CREATE TABLE IF NOT EXISTS ticket_events (
  event_id INT PRIMARY KEY,
  ticket_id INT,
  event_ts DATETIME,
  event_type VARCHAR(40),
  event_note VARCHAR(255),
  FOREIGN KEY (ticket_id) REFERENCES support_tickets(ticket_id)
);


CREATE TABLE IF NOT EXISTS kpi_definitions (
  kpi_id INT PRIMARY KEY,
  kpi_name VARCHAR(120),
  kpi_description VARCHAR(255),
  calculation_rule VARCHAR(255),
  owner_team VARCHAR(60)
);


CREATE TABLE IF NOT EXISTS finance_periods (
  period_id INT PRIMARY KEY,
  fiscal_year INT,
  fiscal_month INT,
  period_start DATE,
  period_end DATE,
  close_status VARCHAR(20)
);

CREATE TABLE IF NOT EXISTS revenue_facts (
  revenue_id INT PRIMARY KEY,
  period_id INT,
  customer_id INT,
  product_id INT,
  recognized_revenue DECIMAL(14,2),
  cost_amount DECIMAL(14,2),
  margin_amount DECIMAL(14,2),
  FOREIGN KEY (period_id) REFERENCES finance_periods(period_id),
  FOREIGN KEY (customer_id) REFERENCES customers(customer_id),
  FOREIGN KEY (product_id) REFERENCES products(product_id)
);

CREATE TABLE IF NOT EXISTS policy_articles (
  article_id INT PRIMARY KEY,
  article_title VARCHAR(160),
  policy_domain VARCHAR(60),
  version_no VARCHAR(20),
  effective_date DATE,
  article_summary VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS workflow_feedback (
  feedback_id INT PRIMARY KEY,
  use_case_name VARCHAR(80),
  actor_role VARCHAR(60),
  event_date DATE,
  confidence_score DECIMAL(5,2),
  adopted_flag CHARACTER(1),
  feedback_note VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS prompt_examples (
 id INTEGER NOT NULL PRIMARY KEY AUTOINCREMENT,
 user_input TEXT NOT NULL,
 sql_query TEXT NOT NULL
);

